def iter_discipline_patterns() -> list[tuple[NucDiscipline | None, str, str, Pattern]]:
    """``(discipline, label, canonical_name, pattern)`` rows; ``None`` is a general skill."""
    rows: list[tuple[NucDiscipline | None, str, str, Pattern]] = [
        (None, label, canonical, pattern)
        for label, canonical, patterns in GENERAL
        for pattern in patterns
    ]
    general = {(label, repr(pattern)) for _, label, _, pattern in rows}
    # The computing list predates disciplines; its general workplace skills are in GENERAL.
    rows.extend(
        (NucDiscipline.COMPUTING, label, canonical, pattern)
        for label, canonical, pattern in iter_skill_patterns()
        if (label, repr(pattern)) not in general
    )
    for discipline, entries in DISCIPLINE_SKILLS.items():
        rows.extend(
            (discipline, label, canonical, pattern)
            for label, canonical, patterns in entries
            for pattern in patterns
        )
    return rows
